"""Build native iOS permission purposes from the app's translated help copy.

No machine translation or English fallback: every supported ARB must provide
the purpose text. Run --check in CI; rerun without it after editing the ARBs.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]


def ident(name):
    return hashlib.sha256(('nshoptor.usage.' + name).encode()).hexdigest()[:24].upper()


def generated():
    outputs = {}
    locales = []
    for arb in sorted((ROOT / 'lib/core/l10n').glob('app_*.arb')):
        locale = arb.stem.removeprefix('app_')
        data = json.loads(arb.read_text(encoding='utf-8'))
        def text(key):
            value = data[key]
            if not isinstance(value, str) or not value.strip() or '{' in value:
                raise ValueError(f'{locale}: invalid purpose source {key}')
            return value.strip()
        values = {
            'NSCameraUsageDescription': text('imageCameraAction') + '. ' + text('guideReceiptBody') + ' ' + text('tipShelfCamera'),
            'NSPhotoLibraryUsageDescription': text('imageGalleryAction') + '. ' + text('guideReceiptBody'),
            'NSMicrophoneUsageDescription': text('guideVoiceBody'),
            'NSSpeechRecognitionUsageDescription': text('guideVoiceBody'),
        }
        # JSON quoting is compatible with UTF-8 OpenStep .strings literals.
        content = '// Generated by tool/ios/localize_usage.py from translated ARB help.\n'
        content += ''.join(f'{json.dumps(k)} = {json.dumps(v, ensure_ascii=False)};\n' for k, v in values.items())
        outputs[ROOT / f'ios/Runner/{locale}.lproj/InfoPlist.strings'] = content
        locales.append(locale)

    project = ROOT / 'ios/Runner.xcodeproj/project.pbxproj'
    source = project.read_text(encoding='utf-8')
    group_id, build_id = ident('group'), ident('build')
    # Remove only this generator's named blocks before recreating them.
    source = re.sub(r'\n/\* BEGIN GENERATED USAGE [A-Z]+ \*/.*?/\* END GENERATED USAGE [A-Z]+ \*/\n', '', source, flags=re.S)
    def block(kind, body):
        return f'\n/* BEGIN GENERATED USAGE {kind} */\n{body}/* END GENERATED USAGE {kind} */\n'
    def before(marker, content):
        nonlocal source
        if source.count(marker) != 1:
            raise ValueError(f'Project marker is ambiguous: {marker}')
        source = source.replace(marker, content + marker)
    before('/* End PBXBuildFile section */', block('BUILD', f'\t\t{build_id} /* InfoPlist.strings in Resources */ = {{isa = PBXBuildFile; fileRef = {group_id} /* InfoPlist.strings */; }};\n'))
    refs = ''.join(f'\t\t{ident(locale)} /* {locale} */ = {{isa = PBXFileReference; lastKnownFileType = text.plist.strings; name = {locale}; path = {locale}.lproj/InfoPlist.strings; sourceTree = "<group>"; }};\n' for locale in locales)
    before('/* End PBXFileReference section */', block('FILES', refs))
    before('\t\t\t\t97C147021CF9000F007C117D /* Info.plist */,', block('GROUP', f'\t\t\t\t{group_id} /* InfoPlist.strings */,\n'))
    before('\t\t\t\t97C147011CF9000F007C117D /* LaunchScreen.storyboard in Resources */,', block('RESOURCE', f'\t\t\t\t{build_id} /* InfoPlist.strings in Resources */,\n'))
    children = ''.join(f'\t\t\t\t{ident(locale)} /* {locale} */,\n' for locale in locales)
    before('/* End PBXVariantGroup section */', block('VARIANT', f'\t\t{group_id} /* InfoPlist.strings */ = {{\n\t\t\tisa = PBXVariantGroup;\n\t\t\tchildren = (\n{children}\t\t\t);\n\t\t\tname = InfoPlist.strings;\n\t\t\tsourceTree = "<group>";\n\t\t}};\n'))
    regions = ''.join(f'\t\t\t\t{locale},\n' for locale in ['Base', *locales])
    source, count = re.subn(r'\t\t\tknownRegions = \(.*?\t\t\t\);', '\t\t\tknownRegions = (\n' + regions + '\t\t\t);', source, count=1, flags=re.S)
    if count != 1:
        raise ValueError('Missing knownRegions')
    outputs[project] = source
    return outputs, len(locales)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs, count = generated()
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise SystemExit(f'Outdated iOS permission localization: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8', newline='\n')
    print(f'iOS permission purposes: {count} locales verified' if args.check else f'iOS permission purposes: {count} locales generated')
